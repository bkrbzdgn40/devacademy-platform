import assert from "node:assert/strict";
import { evaluateExercise } from "../src/evaluate-exercise.mjs";
import { runIsolatedJavaScript } from "../src/run-isolated.mjs";
const correct="function sumEven(numbers){return numbers.filter(n=>n%2===0).reduce((sum,n)=>sum+n,0)}";
const wrong="function sumEven(numbers){return numbers[0]===-3 ? 2 : (numbers[0]===1 ? 0 : 999)}";
const args={exerciseId:"js.sum-even",exerciseRevision:1,image:"node:24-alpine",execute:runIsolatedJavaScript};
const good=await evaluateExercise({...args,source:correct});
assert.equal(good.status,"completed",JSON.stringify(good));
assert.equal(good.assessment.verdict,"passed",JSON.stringify(good));
assert.equal(good.assessment.passed,5);
const bad=await evaluateExercise({...args,source:wrong});
assert.equal(bad.status,"completed",JSON.stringify(bad));
assert.equal(bad.assessment.verdict,"failed");
assert.equal(bad.assessment.passed,2);
assert.equal(bad.assessment.total,5);
assert.equal(bad.assessment.publicCases.every(c=>c.passed),true);
const crash=await evaluateExercise({...args,source:"function sumEven(numbers){throw Error('student blew up')}"});
assert.equal(crash.status,"runtime_error");
assert.equal(crash.assessment,null);
assert.ok(!JSON.stringify(crash).includes("student blew up"));
console.log("Assessment sandbox PASS: passing, public-only-fake and runtime-error solutions distinguished.");
